/** zh for a CTA label: explicit override wins, else the shared map, else none. */
export function ctaZh(label: string | undefined, explicit?: string | null): string | undefined {
  if (explicit) return explicit;
  return label ? CTA_ZH[label.trim()] : undefined;
}
